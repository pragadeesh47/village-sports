
import React, { useState, useEffect } from 'react';
import { db } from '../db';
import type { Game, GameParticipant, Participant, AgeGroup } from '../types';
import { Trophy, Layers, Medal, Star, Share2 } from 'lucide-react';

const Results: React.FC = () => {
  const [gameResults, setGameResults] = useState<any[]>([]);
  const [categories, setCategories] = useState<AgeGroup[]>([]);

  useEffect(() => {
    const fetchResults = async () => {
      const games = await db.games.where('status').equals('COMPLETED').toArray();
      const participants = await db.participants.toArray();
      const gameParts = await db.gameParticipants.toArray();
      const cats = await db.ageGroups.toArray();

      setCategories(cats);

      const results = games.map(game => {
        const winners = gameParts
          .filter(gp => gp.gameId === game.id && gp.position && gp.position > 0)
          .map(gp => ({
            ...gp,
            name: participants.find(p => p.id === gp.participantId)?.name || 'Unknown'
          }))
          .sort((a, b) => (a.position || 0) - (b.position || 0));

        return { ...game, winners };
      });

      setGameResults(results.reverse());
    };
    fetchResults();
  }, []);

  const handleShare = async () => {
    const settings = (await db.settings.toArray())[0];
    let text = `🏡 Village: ${settings?.villageName || 'Our Village'}
🔥 Gang: ${settings?.gangName || 'Our Gang'}
🏆 OFFICIAL GAME RESULTS
--------------------`;

    gameResults.forEach((game, i) => {
      const cat = categories.find(c => c.id === game.ageGroupId)?.name || 'Open Match';
      text += `\n\n${i + 1}. ${game.name.toUpperCase()} (${cat})`;
      if (game.winners.length > 0) {
        game.winners.forEach((w: any) => {
          const posStr = w.position === 1 ? '🥇 1st' : w.position === 2 ? '🥈 2nd' : w.position === 3 ? '🥉 3rd' : `${w.position}th`;
          text += `\n- ${posStr}: ${w.name}`;
        });
      } else {
        text += `\n- No winners recorded`;
      }
      text += `\n--------------------`;
    });

    text += `\n\nGenerated by Village Sports Manager`;

    if (navigator.share) {
      await navigator.share({ title: 'Game Results', text });
    } else {
      await navigator.clipboard.writeText(text);
      alert('Results copied to clipboard!');
    }
  };

  return (
    <div className="p-6 lg:p-10 bg-gray-50 min-h-full">
      <div className="flex flex-col md:flex-row md:items-center justify-between mb-8 gap-4">
        <div>
          <h1 className="text-3xl font-black text-gray-900">Game Results</h1>
          <p className="text-gray-500 font-medium">Official archive of all winners and event rankings</p>
        </div>
        <button 
          onClick={handleShare}
          className="bg-indigo-600 text-white px-6 py-4 rounded-2xl flex items-center gap-2 font-bold shadow-xl active:scale-95 transition-all"
        >
          <Share2 size={20} /> <span>Share Results</span>
        </button>
      </div>

      <div className="space-y-8">
        {gameResults.map(game => (
          <div key={game.id} className="bg-white p-8 rounded-[2.5rem] shadow-sm border border-gray-100 group transition-all">
            <div className="flex items-center justify-between mb-6">
              <div>
                <span className="text-[10px] font-black text-indigo-400 uppercase tracking-widest bg-indigo-50 px-2 py-0.5 rounded-md flex items-center gap-1 w-fit mb-1">
                  <Layers size={10} />
                  {categories.find(c => c.id === game.ageGroupId)?.name || 'Open Match'}
                </span>
                <h2 className="text-2xl font-black text-gray-900 leading-tight">{game.name}</h2>
              </div>
            </div>
            
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4">
              {game.winners.map((w: any) => (
                <div key={w.participantId} className="flex items-center space-x-4 p-4 bg-gray-50 rounded-3xl border border-gray-100">
                  <div className={`w-12 h-12 rounded-2xl flex items-center justify-center font-black text-xl shadow-sm ${
                    w.position === 1 ? 'bg-yellow-400 text-white' :
                    w.position === 2 ? 'bg-gray-300 text-white' :
                    w.position === 3 ? 'bg-orange-400 text-white' : 'bg-indigo-100 text-indigo-400'
                  }`}>
                    {w.position}
                  </div>
                  <div className="flex-1 min-w-0">
                    <p className="text-[10px] font-black text-gray-400 uppercase tracking-widest">
                      {w.position === 1 ? 'Gold' : w.position === 2 ? 'Silver' : w.position === 3 ? 'Bronze' : 'Runner'}
                    </p>
                    <p className="font-bold text-gray-900 truncate text-lg">{w.name}</p>
                  </div>
                </div>
              ))}
              {game.winners.length === 0 && (
                <div className="col-span-full py-4 text-center text-gray-400 font-bold italic text-sm">No positions were recorded for this match.</div>
              )}
            </div>
          </div>
        ))}
        {gameResults.length === 0 && (
          <div className="py-20 text-center">
            <Trophy className="mx-auto text-gray-200 mb-4" size={64} />
            <p className="text-gray-400 font-bold text-xl">No games completed yet.</p>
          </div>
        )}
      </div>
    </div>
  );
};

export default Results;
